function yaoNameFor(pos, isYang) {
  // Standard: 九 for yang, 六 for yin; e.g. 初九, 六二, 九五, 上九
  const cn = toChineseNum(pos);
  if (pos === 1) return isYang ? '初九' : '初六';
  if (pos === 6) return isYang ? '上九' : '上六';
  return isYang ? `九${cn}` : `六${cn}`;
}

