function classifyQuestion(question) {
  if (!question) return 'general';
  const q = question.toLowerCase();
  // 同时匹配简繁体（lawsuit 优先于 career，避免“官司”被“官”抢先匹配）
  if (q.match(/官司|诉讼|诉讼|纠纷|纠纷|合同/)) return 'lawsuit';
  if (q.match(/事业|事业|工作|职场|职场|升官|升职|升职|求职|求职|官运|官运/)) return 'career';
  if (q.match(/感情|婚姻|爱情|爱情|婚|恋|恋|对象|对象|姻缘|姻缘/)) return 'love';
  if (q.match(/财|财|钱|钱|投资|投资|生意|盈利|亏损|亏损/)) return 'wealth';
  if (q.match(/病|健康|身体|身体|疾|医|医/)) return 'health';
  if (q.match(/出行|旅游|旅游|出差|搬家|远行|远行/)) return 'travel';
  if (q.match(/失物|丢|遗失|遗失|寻|寻|找不到/)) return 'lost';
  if (q.match(/考试|考试|升学|升学|考研|学业|学业/)) return 'study';
  return 'general';
}

